"""Pydantic schemas for LLM provider inputs, outputs, and passage contexts."""
from typing import List, Optional
from pydantic import BaseModel, Field, field_validator


class LLMChunkContext(BaseModel):
    """Passage context supplied to the LLM for grounded answer generation."""
    chunk_id: int = Field(..., gt=0, description="Positive 64-bit integer ID of the chunk")
    content: str = Field(..., min_length=1, description="Non-empty passage text extracted from the document")
    page_number: int = Field(..., ge=1, description="1-based physical page number where the passage appears")
    document_title: str = Field(..., min_length=1, description="Title of the source document")

    @field_validator("content", "document_title")
    @classmethod
    def validate_non_whitespace(cls, v: str) -> str:
        if not v or not v.strip():
            raise ValueError("Field must contain non-whitespace characters")
        return v.strip()


class LLMRequest(BaseModel):
    """Standardized request payload passed to an LLM provider."""
    prompt: str = Field(..., min_length=1, description="User query or instruction")
    context_chunks: List[LLMChunkContext] = Field(
        default_factory=list,
        description="List of retrieved passage contexts to be referenced in the answer",
    )
    system_instruction: Optional[str] = Field(
        default=None,
        description="Optional system instruction or role directive for the model",
    )
    temperature: float = Field(
        default=0.0,
        ge=0.0,
        le=2.0,
        description="Sampling temperature between 0.0 and 2.0 (default 0.0 for deterministic answers)",
    )
    max_tokens: Optional[int] = Field(
        default=None,
        gt=0,
        description="Optional upper bound on tokens to generate",
    )

    @field_validator("prompt")
    @classmethod
    def validate_prompt_not_empty(cls, v: str) -> str:
        if not v or not v.strip():
            raise ValueError("Prompt must contain non-whitespace characters")
        return v.strip()


class LLMResponse(BaseModel):
    """Standardized response returned by an LLM provider.

    Design & Architecture Note:
    Preserves raw generated string output (`content`) containing provider-generated
    citation markers (e.g. `[CHUNK:123]`).
    Authoritative citation extraction, verification against retrieved chunk IDs,
    and hallucination pruning are deferred to Phase 4, Milestone 2 (RAG citation validator).
    """
    content: str = Field(..., description="Raw text generated by the LLM provider")
    model_name: str = Field(..., description="Name of the model that generated the completion")
    provider_name: str = Field(..., description="Name of the LLM provider that processed the request")
    finish_reason: str = Field(default="stop", description="Reason generation finished (e.g. 'stop', 'length')")
    prompt_tokens: Optional[int] = Field(default=None, ge=0, description="Input tokens processed, if reported")
    completion_tokens: Optional[int] = Field(default=None, ge=0, description="Output tokens generated, if reported")
    total_tokens: Optional[int] = Field(default=None, ge=0, description="Total tokens used, if reported")
