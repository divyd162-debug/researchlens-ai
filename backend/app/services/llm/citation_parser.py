"""Pure regex-based citation parser for extracting [CHUNK:<id>] markers from text."""
import re
from typing import List, Set
from pydantic import BaseModel, Field

# Maximum 64-bit signed integer supported by PostgreSQL BIGINT / SQLite
MAX_BIGINT = 9223372036854775807

# Matches closed and unclosed marker-like tokens starting with [CHUNK:
_MARKER_LIKE_REGEX = re.compile(r"\[CHUNK\s*:[^\]\r\n]*\]?", re.IGNORECASE)

# Validates exact standard syntax: [CHUNK: <digits>]
_VALID_CHUNK_REGEX = re.compile(r"^\[CHUNK\s*:\s*([0-9]+)\s*\]$", re.IGNORECASE)


def _normalize_brackets(text: str) -> str:
    """Normalizes Unicode lenticular (【 】) and fullwidth (［ ］) brackets to ASCII brackets."""
    if not text:
        return ""
    return (
        text.replace("【", "[")
        .replace("】", "]")
        .replace("［", "[")
        .replace("］", "]")
    )


class ParsedCitations(BaseModel):
    """Structured result of parsing citation markers from text."""
    raw_chunk_ids: List[int] = Field(
        default_factory=list,
        description="Valid chunk IDs in exact order of appearance (may contain duplicates)",
    )
    unique_chunk_ids: List[int] = Field(
        default_factory=list,
        description="Deduplicated valid chunk IDs in first-occurrence order",
    )
    malformed_markers: List[str] = Field(
        default_factory=list,
        description="Marker-like strings that failed validation (e.g. non-integer, zero, negative, unclosed)",
    )
    has_citations: bool = Field(
        default=False,
        description="True if at least one valid citation marker was found",
    )


class CitationParser:
    """Stateless parser for extracting and validating [CHUNK:<id>] marker tags.

    Design Principles:
    1. Pure Parser: Does not mutate the input text or perform database/network lookups.
    2. Strict Validation:
       - Only positive integers (1 <= chunk_id <= 2^63 - 1) are recognized as valid.
       - Zero ([CHUNK:0]), negative numbers ([CHUNK:-1]), non-integers ([CHUNK:abc]),
         empty markers ([CHUNK:]), out-of-range integers, and unclosed brackets are
         safely classified as malformed markers rather than raising exceptions.
    3. Order Preservation:
       - `raw_chunk_ids` preserves the exact sequence of citations in the text.
       - `unique_chunk_ids` deduplicates while strictly preserving first-occurrence order.
    """

    @classmethod
    def parse(cls, text: str) -> ParsedCitations:
        """Parses citation markers from text and returns structured extraction results.

        Args:
            text: Raw string generated by an LLM or user.

        Returns:
            ParsedCitations containing valid IDs and any malformed marker strings.
        """
        if not text or not isinstance(text, str):
            return ParsedCitations(
                raw_chunk_ids=[],
                unique_chunk_ids=[],
                malformed_markers=[],
                has_citations=False,
            )

        # Normalize Unicode bracket variants (lenticular 【 】, fullwidth ［ ］) to standard [ ]
        normalized_text = _normalize_brackets(text)

        raw_ids: List[int] = []
        unique_ids: List[int] = []
        seen_ids: Set[int] = set()
        malformed: List[str] = []

        for match in _MARKER_LIKE_REGEX.finditer(normalized_text):
            token = match.group(0).strip()

            # 1. Check for unclosed bracket
            if not token.endswith("]"):
                malformed.append(token)
                continue

            # 2. Check for valid format: [CHUNK: <digits>]
            valid_match = _VALID_CHUNK_REGEX.match(token)
            if not valid_match:
                malformed.append(token)
                continue

            # 3. Parse and bounds-check integer
            digits_str = valid_match.group(1)
            try:
                chunk_id = int(digits_str)
            except (ValueError, OverflowError):
                malformed.append(token)
                continue

            # Positive integer required (chunks table IDs start at 1) and <= MAX_BIGINT
            if chunk_id <= 0 or chunk_id > MAX_BIGINT:
                malformed.append(token)
                continue

            raw_ids.append(chunk_id)
            if chunk_id not in seen_ids:
                seen_ids.add(chunk_id)
                unique_ids.append(chunk_id)

        return ParsedCitations(
            raw_chunk_ids=raw_ids,
            unique_chunk_ids=unique_ids,
            malformed_markers=malformed,
            has_citations=len(raw_ids) > 0,
        )
